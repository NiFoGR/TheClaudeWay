// Escaping and icons for every page's HTML: esc() for any text put into HTML (attributes too), safeUrl() for any link
// that came from outside (http(s) only, else ""), icon() for the inline SVG icons. Pure: it never reads the page, so
// node tests and pure renderers (leadview.js and later stages' views) import it directly; lib.js re-exports all three.
// Every value from scraped websites, inbound mail or Claude goes through esc()/safeUrl() before it touches the page.

export const esc = (v) => String(v ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);

export function safeUrl(u) {
  try {
    const url = new URL(u);
    return url.protocol === "https:" || url.protocol === "http:" ? url.href : "";
  } catch {
    return "";
  }
}

